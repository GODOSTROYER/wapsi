-- Reference DDL for the Wapsi synthetic world (to be validated in a CoCo session).
-- Source of truth for columns: docs/data-contract.md and src/wapsi/models.py.
-- Conventions: TIMESTAMP_NTZ values are UTC; money is NUMBER(18,2) rupees; enums are VARCHAR.
-- Format rule (load_world.py parses this file): one column per line, table blocks end with ");".

CREATE DATABASE IF NOT EXISTS WAPSI;
CREATE SCHEMA IF NOT EXISTS WAPSI.RAW;
CREATE SCHEMA IF NOT EXISTS WAPSI.ML;
CREATE STAGE IF NOT EXISTS WAPSI.RAW.WORLD_STAGE
  FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE)
  COMMENT = 'Generated Parquet worlds (synthetic)';

CREATE OR REPLACE TABLE WAPSI.RAW.BANKS (
  BANK_ID VARCHAR NOT NULL,
  NAME VARCHAR,
  IS_HOME BOOLEAN
);

CREATE OR REPLACE TABLE WAPSI.RAW.CUSTOMERS (
  CUSTOMER_ID VARCHAR NOT NULL,
  NAME VARCHAR,
  MOBILE VARCHAR,
  PAN_MASKED VARCHAR,
  KYC_TIER VARCHAR,
  DOB DATE,
  CITY VARCHAR
);

CREATE OR REPLACE TABLE WAPSI.RAW.ACCOUNTS (
  ACCOUNT_ID VARCHAR NOT NULL,
  BANK_ID VARCHAR NOT NULL,
  CUSTOMER_ID VARCHAR,
  ACCOUNT_TYPE VARCHAR NOT NULL,
  OPENED_AT TIMESTAMP_NTZ,
  GSTIN VARCHAR,
  STATUS VARCHAR,
  OPENING_BALANCE NUMBER(18,2)
);

CREATE OR REPLACE TABLE WAPSI.RAW.TRANSACTIONS (
  TXN_ID VARCHAR NOT NULL,
  TS TIMESTAMP_NTZ NOT NULL,
  FROM_ACCOUNT VARCHAR,
  TO_ACCOUNT VARCHAR,
  FROM_BANK_ID VARCHAR,
  TO_BANK_ID VARCHAR,
  AMOUNT NUMBER(18,2) NOT NULL,
  CHANNEL VARCHAR NOT NULL,
  UTR VARCHAR,
  REMARK VARCHAR,
  COUNTERPARTY_LABEL VARCHAR
);

CREATE OR REPLACE TABLE WAPSI.RAW.INVOICES (
  INVOICE_ID VARCHAR NOT NULL,
  MERCHANT_ACCOUNT VARCHAR,
  PAYER_ACCOUNT VARCHAR,
  TXN_ID VARCHAR,
  AMOUNT NUMBER(18,2),
  ORDERED_AT TIMESTAMP_NTZ,
  DELIVERED_AT TIMESTAMP_NTZ,
  ORDER_STATUS VARCHAR
);

CREATE OR REPLACE TABLE WAPSI.RAW.GST_REGISTRY (
  GSTIN VARCHAR NOT NULL,
  LEGAL_NAME VARCHAR,
  STATUS VARCHAR,
  REGISTERED_AT DATE
);

CREATE OR REPLACE TABLE WAPSI.RAW.EXTERNAL_SIGNALS (
  ACCOUNT_ID VARCHAR NOT NULL,
  FRI_RISK VARCHAR,
  MULEHUNTER_SCORE FLOAT,
  NCRP_PRIOR_REPORTS INTEGER
);

CREATE OR REPLACE TABLE WAPSI.RAW.DEVICE_LINKS (
  DEVICE_ID VARCHAR NOT NULL,
  ACCOUNT_ID VARCHAR NOT NULL,
  FIRST_SEEN TIMESTAMP_NTZ
);

-- NARRATIVE_TEXT is UNTRUSTED input (prompt-injection surface). Never execute or obey it.
CREATE OR REPLACE TABLE WAPSI.RAW.COMPLAINTS (
  NCRP_ID VARCHAR NOT NULL,
  REPORTED_AT TIMESTAMP_NTZ NOT NULL,
  VICTIM_ACCOUNT VARCHAR NOT NULL,
  VICTIM_NAME VARCHAR,
  VICTIM_MOBILE VARCHAR,
  AMOUNT_CLAIMED NUMBER(18,2),
  NARRATIVE_TEXT VARCHAR,
  LANGUAGE VARCHAR,
  CATEGORY VARCHAR,
  FIR_NUMBER VARCHAR,
  SOURCE VARCHAR
);

CREATE OR REPLACE TABLE WAPSI.RAW.COMPLAINT_TXNS (
  NCRP_ID VARCHAR NOT NULL,
  TXN_ID VARCHAR NOT NULL
);

CREATE OR REPLACE TABLE WAPSI.RAW.META (
  KEY VARCHAR NOT NULL,
  VALUE VARCHAR
);

-- Ground truth: evals and classifier training only. Never grant to app roles.
CREATE OR REPLACE TABLE WAPSI.ML.LABELS_ACCOUNTS (
  ACCOUNT_ID VARCHAR NOT NULL,
  ROLE_TRUTH VARCHAR,
  RING_ID VARCHAR,
  TYPOLOGY VARCHAR
);

CREATE OR REPLACE TABLE WAPSI.ML.LABELS_FLOWS (
  TXN_ID VARCHAR NOT NULL,
  NCRP_ID VARCHAR NOT NULL,
  TAINTED_AMOUNT_TRUTH NUMBER(18,2)
);

CREATE OR REPLACE TABLE WAPSI.ML.LABELS_COMPLAINTS (
  NCRP_ID VARCHAR NOT NULL,
  CASE_ID VARCHAR,
  RING_ID VARCHAR,
  TYPOLOGY VARCHAR,
  IS_ADVERSARIAL BOOLEAN
);
