"""Load a generated Wapsi world (Parquet) into Snowflake WAPSI.RAW / WAPSI.ML.

Part of the `synth-fraud-ledger` skill. Run from the repo root.

    # plan only (no Snowflake): row counts + column check against references/raw_ddl.sql
    uv run python .claude/skills/synth-fraud-ledger/scripts/load_world.py --world data/generated/demo --dry-run

    # print PUT / COPY INTO statements for SnowSQL or `snow sql -f`
    uv run python .claude/skills/synth-fraud-ledger/scripts/load_world.py --world data/generated/demo --emit-sql

    # load with Snowpark write_pandas (needs a connection in ~/.snowflake/connections.toml)
    uv run --with "snowflake-snowpark-python[pandas]" python \
        .claude/skills/synth-fraud-ledger/scripts/load_world.py --world data/generated/demo --connection wapsi --create

Exit codes: 0 ok, 1 mismatch (columns or row counts), 2 usage / missing input.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

SKILL_DIR = Path(__file__).resolve().parents[1]
DDL_PATH = SKILL_DIR / "references" / "raw_ddl.sql"
DATABASE = "WAPSI"
GROUND_TRUTH_PREFIX = "labels_"
# load order: parents first (not enforced by Snowflake, but keeps partial failures readable)
ORDER = [
    "meta",
    "banks",
    "customers",
    "accounts",
    "gst_registry",
    "external_signals",
    "device_links",
    "transactions",
    "invoices",
    "complaints",
    "complaint_txns",
    "labels_accounts",
    "labels_flows",
    "labels_complaints",
]


def schema_for(table: str) -> str:
    return "ML" if table.startswith(GROUND_TRUTH_PREFIX) else "RAW"


def parse_ddl(path: Path = DDL_PATH) -> tuple[dict[str, dict[str, str]], list[str]]:
    """Return ({TABLE: {COLUMN: TYPE}}, [statements]) from the reference DDL."""
    text = "\n".join(
        line for line in path.read_text(encoding="utf-8").splitlines() if not line.strip().startswith("--")
    )
    statements = [s.strip() for s in text.split(";") if s.strip()]
    tables: dict[str, dict[str, str]] = {}
    for stmt in statements:
        m = re.match(
            r"CREATE OR REPLACE TABLE\s+WAPSI\.(\w+)\.(\w+)\s*\(\s*\n(.*?)\n\s*\)", stmt, re.S | re.I
        )
        if not m:
            continue
        cols: dict[str, str] = {}
        for line in m.group(3).splitlines():
            line = line.strip().rstrip(",")
            name, _, typ = line.partition(" ")
            typ = typ.split(" NOT NULL")[0].strip()
            if not name or not typ:
                continue
            cols[name.upper()] = typ
        tables[m.group(2).upper()] = cols
    return tables, statements


def discover(world: Path) -> list[str]:
    found = {p.stem for p in world.glob("*.parquet")}
    ordered = [t for t in ORDER if t in found]
    return ordered + sorted(found - set(ordered))


def read_frame(path: Path):
    import pandas as pd
    import pyarrow.parquet as pq

    df = pq.read_table(path).to_pandas()
    for col in df.columns:
        if isinstance(df[col].dtype, pd.DatetimeTZDtype):
            # store UTC wall-clock in TIMESTAMP_NTZ (convention: store UTC, display IST)
            df[col] = df[col].dt.tz_convert("UTC").dt.tz_localize(None)
    df.columns = [c.upper() for c in df.columns]
    return df


def check_columns(table: str, df_cols: list[str], ddl: dict[str, dict[str, str]]) -> list[str]:
    expected = ddl.get(table.upper())
    if expected is None:
        return [f"{table}: no DDL block in {DDL_PATH.name}"]
    problems = []
    missing = [c for c in expected if c not in df_cols]
    extra = [c for c in df_cols if c not in expected]
    if missing:
        problems.append(f"{table}: DDL columns missing from Parquet: {missing}")
    if extra:
        problems.append(f"{table}: Parquet columns not in DDL: {extra}")
    return problems


def emit_sql(world: Path, tables: list[str], ddl: dict[str, dict[str, str]]) -> str:
    stage = f"@{DATABASE}.RAW.WORLD_STAGE/{world.name}"
    out = [
        "-- Generated by synth-fraud-ledger/load_world.py. Review before running (SnowSQL or `snow sql -f`).",
        "-- PUT does not run in Snowsight worksheets.",
        "USE DATABASE WAPSI;",
        "ALTER SESSION SET TIMEZONE = 'UTC';",
    ]
    for t in tables:
        fq = f"{DATABASE}.{schema_for(t)}.{t.upper()}"
        local = (world / f"{t}.parquet").resolve().as_posix()
        out += [
            "",
            f"PUT 'file://{local}' {stage}/ AUTO_COMPRESS = FALSE OVERWRITE = TRUE;",
            f"TRUNCATE TABLE IF EXISTS {fq};",
            f"COPY INTO {fq}",
            f"  FROM {stage}/{t}.parquet",
            "  FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE)",
            "  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE",
            "  ON_ERROR = ABORT_STATEMENT;",
        ]
        cols = ddl.get(t.upper(), {})
        if cols:
            names = ", ".join(cols)
            sel = ", ".join(f'$1:"{c.lower()}"::{typ.split()[0]}' for c, typ in cols.items())
            out.append("-- fallback if MATCH_BY_COLUMN_NAME rejects empty strings:")
            out.append(
                f"-- COPY INTO {fq} ({names}) FROM (SELECT {sel} FROM {stage}/{t}.parquet)"
                " FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE) ON_ERROR = ABORT_STATEMENT;"
            )
    out += ["", "-- row counts"]
    out.append(
        "\nUNION ALL\n".join(
            f"SELECT '{t.upper()}' AS table_name, COUNT(*) AS n FROM {DATABASE}.{schema_for(t)}.{t.upper()}"
            for t in tables
        )
        + ";"
    )
    return "\n".join(out)


def connect(connection: str):
    try:
        from snowflake.snowpark import Session
    except ImportError:
        sys.exit(
            "snowflake-snowpark-python is not installed. Re-run with:\n"
            '  uv run --with "snowflake-snowpark-python[pandas]" python ' + " ".join(sys.argv)
        )
    session = Session.builder.config("connection_name", connection).create()
    session.sql("ALTER SESSION SET TIMEZONE = 'UTC'").collect()
    return session


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--world", required=True, help="directory with <table>.parquet files")
    ap.add_argument("--connection", default="wapsi", help="connection name in connections.toml")
    ap.add_argument("--dry-run", action="store_true", help="no Snowflake: print plan and column check")
    ap.add_argument("--emit-sql", action="store_true", help="print PUT/COPY statements and exit")
    ap.add_argument("--create", action="store_true", help="run references/raw_ddl.sql before loading")
    ap.add_argument("--tables", nargs="*", help="subset of tables (default: all Parquet files found)")
    args = ap.parse_args(argv)

    world = Path(args.world)
    if not world.is_dir():
        print(f"world directory not found: {world} (run `uv run python -m wapsi.synth ... --out {world}`)")
        return 2
    tables = args.tables or discover(world)
    if not tables:
        print(f"no *.parquet files in {world}")
        return 2
    ddl, statements = parse_ddl()

    if args.emit_sql:
        print(emit_sql(world, tables, ddl))
        return 0

    frames = {}
    problems: list[str] = []
    for t in tables:
        df = read_frame(world / f"{t}.parquet")
        frames[t] = df
        problems += check_columns(t, list(df.columns), ddl)

    print(f"World: {world}  ->  {DATABASE}.RAW / {DATABASE}.ML")
    print(f"{'table':<22}{'schema':<8}{'rows':>12}  columns")
    for t, df in frames.items():
        print(f"{t:<22}{schema_for(t):<8}{len(df):>12}  {len(df.columns)}")
    if problems:
        print("\nCOLUMN MISMATCH:")
        for p in problems:
            print(f"  - {p}")
        return 1
    if args.dry_run:
        print("\nDry run OK: columns match the reference DDL. Nothing was sent to Snowflake.")
        return 0

    session = connect(args.connection)
    if args.create:
        for stmt in statements:
            session.sql(stmt).collect()
        print(f"Ran {len(statements)} DDL statements from {DDL_PATH.name}")

    failures = 0
    print(f"\n{'table':<22}{'parquet':>12}{'snowflake':>12}  status")
    for t, df in frames.items():
        schema = schema_for(t)
        name = t.upper()
        session.sql(f"TRUNCATE TABLE IF EXISTS {DATABASE}.{schema}.{name}").collect()
        if len(df):
            session.write_pandas(
                df,
                name,
                database=DATABASE,
                schema=schema,
                quote_identifiers=True,
                auto_create_table=False,
                overwrite=False,
                use_logical_type=True,
            )
        n = session.sql(f"SELECT COUNT(*) AS N FROM {DATABASE}.{schema}.{name}").collect()[0]["N"]
        ok = n == len(df)
        failures += not ok
        print(f"{t:<22}{len(df):>12}{n:>12}  {'OK' if ok else 'MISMATCH'}")
    session.close()
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
