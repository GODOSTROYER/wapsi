"""Render the committed ``data/docs/MANIFEST.md`` from ``raw/_fetch.json`` and ``index/build_report.json``."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from wapsi.search.sources import BUILD_REPORT, CASE_LAW_URLS, FETCH_LOG, MANIFEST_MD, SOURCES


def _read(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def _pages_summary(doc: dict[str, Any]) -> str:
    if not doc:
        return "not built"
    if doc.get("kind") != "pdf":
        return f"HTML, {doc.get('chars', 0):,} chars"
    parts = [f"{doc['pages']} pages, text layer on {doc['text_pages']}"]
    if doc.get("scanned_pages"):
        parts.append(f"no text layer (scanned): {doc['scanned_pages']}")
    if doc.get("blank_pages"):
        parts.append(f"blank: {doc['blank_pages']}")
    return "; ".join(parts)


def render_manifest(fetch_log: dict[str, Any], build: dict[str, Any]) -> str:
    docs = build.get("docs", {})
    out = [
        "# Legal / regulatory corpus manifest",
        "",
        "Generated by `uv run python -m wapsi.search.fetch` / `uv run python -m wapsi.search.build`; do not edit.",
        "Raw files live in `data/docs/raw/` and extracted text/index in `data/docs/index/` (both gitignored,",
        "not redistributed). Only this manifest, `sources.json`, `citations.json` (verbatim quotes <= 25 words),",
        "`facts.json` and `README.md` are committed.",
        "",
        "| doc_id | document | retrieved from | bytes | sha256 | retrieved (UTC) | extraction |",
        "|---|---|---|---:|---|---|---|",
    ]
    for s in SOURCES:
        e = fetch_log.get(s.id, {})
        url = e.get("url") or "-"
        via = " (mirror)" if e.get("via_mirror") else ""
        sha = e.get("sha256", "-")
        out.append(
            f"| `{s.id}` | {s.title} | {url}{via} | {e.get('bytes', 0):,} | `{sha}` | "
            f"{e.get('retrieved_at', 'not fetched')} | {_pages_summary(docs.get(s.id, {}))} |"
        )
    out += ["", "## Sources, mirrors and licences", ""]
    for s in SOURCES:
        e = fetch_log.get(s.id, {})
        out.append(f"### `{s.id}`")
        out.append(f"- Publisher: {s.publisher}")
        out.append(f"- Primary URL: {s.url}")
        for m in s.mirrors:
            status = next((c["status"] for c in e.get("mirror_check", []) if c["url"] == m), None)
            out.append(
                f"- Mirror: {m}" + (f" (checked {e.get('mirror_checked_at')}: {status})" if status else "")
            )
        for att in e.get("failed_attempts", []):
            out.append(f"- Failed attempt: {att['url']} -> {att['error']}")
        out.append(f"- Licence / use: {s.licence}")
        if s.notes:
            out.append(f"- Notes: {s.notes}")
        d = docs.get(s.id)
        if d:
            out.append(f"- Chunks indexed: {d.get('chunks', 0)}; sections detected: {d.get('sections', 0)}")
            if d.get("missing_sections"):
                out.append(f"- Expected sections NOT detected: {', '.join(d['missing_sections'])}")
            for w in d.get("warnings", []):
                out.append(f"- Warning: {w}")
        out.append("")
    out += [
        "## Case law (URLs only; no text fetched or stored)",
        "",
        *[f"- `{cid}`: {url}" for cid, url in CASE_LAW_URLS.items()],
        "- `CASE-SAJEER`, `CASE-SAIFULLAH`: quoted from the summaries in SOP Annexure-III (`sop-2026`).",
        "",
    ]
    if build:
        out += [f"Index built: {build.get('built_at', '?')} ({build.get('total_chunks', 0)} chunks).", ""]
    return "\n".join(out)


def write_manifest(path: Path = MANIFEST_MD) -> Path:
    text = render_manifest(_read(FETCH_LOG), _read(BUILD_REPORT))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    return path
