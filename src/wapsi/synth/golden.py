"""Golden set: one ``GoldenCase`` per case (complaints sharing first-layer accounts), computed by the independent
reference implementation (``wapsi.synth.reference``)."""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

import pandas as pd

from wapsi.models import Disposition, GoldenCase, Role, TraceTotals
from wapsi.money import fmt_inr, r2
from wapsi.synth.reference import RefCase, ReferenceWorld, us_to_dt

TOTAL_KEYS = ["stolen", "holdable", "cashed_out", "outbound", "intermediary", "merchant_settled", "unlocated"]


def compute_cases(frames: dict[str, pd.DataFrame], world: str) -> list[RefCase]:
    ref = ReferenceWorld(frames)
    lc = frames["labels_complaints"][["ncrp_id", "case_id"]]
    comp = frames["complaints"][["ncrp_id", "reported_at"]]
    merged = lc.merge(comp, on="ncrp_id", how="inner")
    cases = []
    for case_id, g in merged.groupby("case_id", sort=True):
        g = g.sort_values(["reported_at", "ncrp_id"], kind="mergesort")
        cases.append(ref.trace(g["ncrp_id"].tolist(), case_id=str(case_id)))
    return cases


def golden_cases(frames: dict[str, pd.DataFrame], cases: list[RefCase], world: str) -> list[GoldenCase]:
    la = frames["labels_accounts"]
    roles = dict(zip(la["account_id"], la["role_truth"].astype(str), strict=True))
    lc = frames["labels_complaints"].set_index("ncrp_id")
    meta = dict(zip(frames["meta"]["key"], frames["meta"]["value"], strict=True))
    out = []
    for c in cases:
        info = lc.loc[c.ncrp_ids]
        touched = sorted(a for a, st in c.accounts.items() if st.layer >= 1)
        fwd = {d.account_id: d.forward_hold_amount for d in c.decisions if d.forward_hold_amount > 0}
        max_layer = max((c.accounts[a].layer for a in touched), default=0)
        notes = {
            "victims": len(c.ncrp_ids),
            "max_layer": max_layer,
            "total_hold": c.total_hold,
            "total_recoverable": c.total_recoverable,
            "forward_hold": fwd,
            "baseline_freeze_amount": c.baseline_freeze_amount,
            "baseline_freeze_accounts": c.baseline_freeze_accounts,
            "window_end": us_to_dt(c.window_end_us).isoformat(),
        }
        if meta.get("size") == "showcase":
            notes["source"] = "wapsi.fixtures.showcase"
        out.append(
            GoldenCase(
                case_id=c.case_id,
                world=world,
                ncrp_ids=list(c.ncrp_ids),
                typology=str(info["typology"].iloc[0]),
                ring_id=str(info["ring_id"].iloc[0]),
                is_adversarial=bool(info["is_adversarial"].astype(bool).any()),
                expected_totals=TraceTotals(**{k: c.totals[k] for k in TOTAL_KEYS}),
                expected_roles={a: Role(roles.get(a, Role.UNKNOWN.value)) for a in touched},
                expected_dispositions={
                    d.account_id: d.disposition for d in sorted(c.decisions, key=lambda d: d.account_id)
                },
                expected_hold={
                    d.account_id: d.hold_amount for d in sorted(c.decisions, key=lambda d: d.account_id)
                },
                expected_outbound_request={
                    d.account_id: d.tainted_amount
                    for d in sorted(c.decisions, key=lambda d: d.account_id)
                    if d.disposition == Disposition.OUTBOUND_CFCFRMS_REQUEST
                },
                expected_per_victim_recoverable=dict(c.per_victim_recoverable),
                expected_process=c.process,
                expected_str_ground=c.str_ground,
                expected_escalation_candidates=list(c.escalation_candidates),
                notes=json.dumps(notes, sort_keys=True, ensure_ascii=False),
            )
        )
    return sorted(out, key=lambda g: g.case_id)


def _inr(x: float) -> str:
    return fmt_inr(x, paise=False)


def summary_markdown(frames: dict[str, pd.DataFrame], golden: list[GoldenCase]) -> str:
    meta = dict(zip(frames["meta"]["key"], frames["meta"]["value"], strict=True))
    lines = [
        f"# Golden set — world `{meta.get('world')}`",
        "",
        f"Generated by `{meta.get('generator_version')}` (size `{meta.get('size')}`, seed `{meta.get('seed')}`). "
        "Expected values come from the independent reference implementation `wapsi.synth.reference` "
        "(pro-rata, default `TraceConfig`, balances as of `world_end`). All data is synthetic.",
        "",
        "| World | Value |",
        "|---|---|",
    ]
    for k in [
        "world_start",
        "world_end",
        "home_bank_id",
        "n_accounts",
        "n_transactions",
        "n_rings",
        "n_episodes",
        "n_complaints",
        "n_cases",
        "n_adversarial",
        "reference_warnings",
    ]:
        lines.append(f"| {k} | {meta.get(k, '')} |")
    lines += [
        "",
        "## Cases by typology",
        "",
        "| Typology | Cases | Complaints | Adversarial | P2 | s.106 flags | Stolen | Holdable | Cashed out | "
        "Outbound | Intermediary | Merchant settled | Total hold | Total recoverable |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    by: dict[str, list[GoldenCase]] = {}
    for g in golden:
        by.setdefault(g.typology, []).append(g)

    def row(label: str, gs: list[GoldenCase]) -> str:
        t = {k: r2(sum(getattr(g.expected_totals, k) for g in gs)) for k in TOTAL_KEYS}
        notes = [json.loads(g.notes) for g in gs]
        hold = r2(sum(n["total_hold"] for n in notes))
        rec = r2(sum(n["total_recoverable"] for n in notes))
        return (
            f"| {label} | {len(gs)} | {sum(len(g.ncrp_ids) for g in gs)} | {sum(g.is_adversarial for g in gs)} | "
            f"{sum(g.expected_process.value == 'P2' for g in gs)} | "
            f"{sum(len(g.expected_escalation_candidates) for g in gs)} | {_inr(t['stolen'])} | "
            f"{_inr(t['holdable'])} | {_inr(t['cashed_out'])} | {_inr(t['outbound'])} | "
            f"{_inr(t['intermediary'])} | {_inr(t['merchant_settled'])} | {_inr(hold)} | {_inr(rec)} |"
        )

    for typ in sorted(by, key=lambda s: int(s.split("_")[0][1:])):
        lines.append(row(f"`{typ}`", by[typ]))
    lines.append(row("**All**", golden))
    disp = Counter(d.value for g in golden for d in g.expected_dispositions.values())
    roles = Counter(r.value for g in golden for r in g.expected_roles.values())
    lines += ["", "## Dispositions (all cases)", "", "| Disposition | Accounts |", "|---|---:|"]
    lines += [f"| `{k}` | {v} |" for k, v in sorted(disp.items())]
    lines += ["", "## Roles of tainted accounts", "", "| Role | Accounts |", "|---|---:|"]
    lines += [f"| `{k}` | {v} |" for k, v in sorted(roles.items())]
    unl = [g.case_id for g in golden if abs(g.expected_totals.unlocated) > 0.05]
    lines += ["", f"Cases with |unlocated| > ₹0.05 (rounding only otherwise): {len(unl)}", ""]
    return "\n".join(lines)


def write_golden(
    frames: dict[str, pd.DataFrame], cases: list[RefCase], out_dir: str | Path, world: str
) -> list[GoldenCase]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    golden = golden_cases(frames, cases, world)
    with (out / "cases.jsonl").open("w", encoding="utf-8", newline="\n") as fh:
        for g in golden:
            fh.write(g.model_dump_json() + "\n")
    (out / "SUMMARY.md").write_text(summary_markdown(frames, golden), encoding="utf-8", newline="\n")
    return golden


def load_golden(path: str | Path) -> list[GoldenCase]:
    p = Path(path)
    if p.is_dir():
        p = p / "cases.jsonl"
    return [
        GoldenCase.model_validate_json(line) for line in p.read_text(encoding="utf-8").splitlines() if line
    ]
