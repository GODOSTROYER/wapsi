def _marker(sid: str) -> re.Pattern[str]:
    return re.compile(rf"<!-- slot:{re.escape(sid)} -->(?P<v>.*?)<!-- /slot -->", re.S)


def _anchor(slot: Slot) -> re.Pattern[str]:
    """The slot by the literal text around it: the placeholder, or an earlier fill, between ``before`` and
    ``after``. A marker-only slot has no such text: this is then its bare marker."""
    if slot.marker_only:
        return _marker(slot.sid)
    filled = rf"<!-- slot:{re.escape(slot.sid)} -->.*?<!-- /slot -->"
    return re.compile(re.escape(slot.before) + rf"(?P<v>{re.escape(slot.placeholder)}|{filled})" + re.escape(slot.after))


@dataclass
class Found:
    """One place of a slot in one file: the span to replace and whether it still shows its placeholder."""

    file: str
    start: int
    end: int
    empty: bool


def find(slot: Slot, texts: dict[str, str]) -> list[Found]:
    """Where the slot is. By its anchor text in its file; failing that (the author reworded the page), or for a
    marker-only slot, by its bare marker in any of ``texts``."""
    out: list[Found] = []
    if not slot.marker_only and slot.file in texts:
        for m in _anchor(slot).finditer(texts[slot.file]):
            out.append(Found(slot.file, m.start("v"), m.end("v"), m.group("v") == slot.placeholder))
        if out:
            return out
    for rel, text in texts.items():
        if Path(rel).name in SKIP_MARKER_FILES:
            continue
        for m in _marker(slot.sid).finditer(text):
            inner = m.group("v").strip()
            out.append(Found(rel, m.start(), m.end(), inner == "" or "TBD" in inner or inner == slot.placeholder))
    return out


def render(slot: Slot, head: dict[str, Any], date: str, where: str = "MI300X") -> tuple[
        str | None, list[tuple[str, str, str, str]]]:
    """(text for the slot or None when a value is missing, [(key, formatted text, value string, what)])."""
    texts, rows = {}, []
    for i, (key, fmt, what) in enumerate(slot.keys):
        v = head.get(key)
        if not isinstance(v, int | float) or isinstance(v, bool):
            if key == "e2e_best_inr_per_case":  # rupees need the day's rate; the dollar figure stands alone
                texts[f"k{i}"] = None
                continue
            return None, []
        texts[f"k{i}"] = fmt.text(float(v))
        rows.append((key, texts[f"k{i}"], fmt.value(float(v)), what))
    template = slot.template
    if any(t is None for t in texts.values()):
        template = template.replace(" ({k1})", "")
    return template.format(date=date, where=where, **{k: t for k, t in texts.items() if t is not None}), rows


@dataclass
class NumRow:
    """One generated ``NUMBERS.md`` row: ``| amd_<key>[_<date>] | pitched | value | source | `json:headline.<key>` |``."""

    rid: str
    pitched: str
    value: str
    source: str
    key: str

    def line(self) -> str:
        return f"| {self.rid} | {self.pitched} | {self.value} | {self.source} | `json:headline.{self.key}` |"


def _date_of(source: str) -> str:
    """The UTC date folder of an evidence bundle path (``.../2026-10-12/evidence.json`` -> ``2026-10-12``)."""
    found = re.findall(r"\d{4}-\d{2}-\d{2}", source)
    return found[-1] if found else "undated"


def existing_rows(numbers_text: str) -> list[NumRow]:
    """The rows of the generated section already in NUMBERS.md (empty when there is none)."""
    start = numbers_text.find(BEGIN.split(" (")[0])
    end = numbers_text.find(END)
    if start < 0 or end < start:
        return []
    rows = []
    for line in numbers_text[start:end].splitlines():
        if not line.startswith("| amd_"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        locator = cells[4].strip("`") if len(cells) == 5 else ""
        if locator.startswith("json:headline."):
            rows.append(NumRow(cells[0], cells[1], cells[2], cells[3], locator.removeprefix("json:headline.")))
    return rows


def merge_rows(old: list[NumRow], new: dict[str, tuple[str, set[str], str]], source: str,
               still_shown: set[str]) -> list[NumRow]:
    """The new bundle's rows, plus every earlier row it does not replace.

    An earlier row is replaced when the new bundle measured its key, unless that key is also in a slot the new
    bundle could not refill (``still_shown``): the older value is then still on the page, so its row stays, renamed
    ``amd_<key>_<date>`` to keep ids unique."""
    out: dict[str, NumRow] = {}
    for key in sorted(new):
        what, shown, value = new[key]
        pitched = f"{'; '.join(sorted(shown))} ({what})".replace("|", "/")
        out[f"amd_{key}"] = NumRow(f"amd_{key}", pitched, value, source, key)
    for row in old:
        if row.key in new:
            if row.source == source or row.key not in still_shown:
                continue
            row = replace(row, rid=f"amd_{row.key}_{_date_of(row.source).replace('-', '')}")
        out.setdefault(row.rid, row)
    return sorted(out.values(), key=lambda r: (r.key, r.rid))


# --------------------------------------------------------------------------- what a bundle may claim


def mode_of(ev: dict[str, Any]) -> str:
    """``droplet`` | ``notebook`` | ``endpoint`` | ``cpu-rehearsal`` (``gpu``: the droplet's name in older bundles)."""
    mode = str(ev.get("mode") or "")
    return "droplet" if mode == "gpu" else mode


def where_of(ev: dict[str, Any]) -> str:
    """The place name a slot may print (``compute.short``; older droplet bundles: MI300X)."""
    return str((ev.get("compute") or {}).get("short") or "MI300X")


def is_mi300x(ev: dict[str, Any]) -> bool:
    name = (ev.get("headline") or {}).get("gpu_name") or (ev.get("compute") or {}).get("gpu_name")
    return mode_of(ev) in OWN_GPU and "MI300" in str(name or "")


def drafting_models(ev: dict[str, Any]) -> list[str]:
    """Every name the bundle gives the drafting model (endpoint model id, the plan, the served profile)."""
    head, run = ev.get("headline") or {}, ev.get("run") or {}
    plan = (((ev.get("results") or {}).get("endpoint") or {}).get("model_plan") or {}).get("drafting") or {}
    names = [head.get("model_id"), plan.get("id"), run.get("served_profile"), head.get("drafting_model_planned")]
    return list(dict.fromkeys(str(n) for n in names if n))


def is_gemma(ev: dict[str, Any]) -> bool:
    """False only when the bundle names its drafting model and no name is a Gemma one (a bundle that names none,
    e.g. an older droplet bundle, is taken as the default Gemma run)."""
    names = drafting_models(ev)
    return not names or any("gemma" in n.lower() for n in names)


_BUNDLES: dict[str, dict[str, Any]] = {}


def _bundle(source: str) -> dict[str, Any]:
    """The evidence bundle a NUMBERS.md row names in its Source ({} when it cannot be read)."""
    if source not in _BUNDLES:
        path = Path(source) if Path(source).is_absolute() else ROOT / source
        try:
            _BUNDLES[source] = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            _BUNDLES[source] = {}
    return _BUNDLES[source]


def _join(parts: list[str]) -> str:
    return parts[0] if len(parts) == 1 else ", ".join(parts[:-1]) + " and " + parts[-1]


@dataclass
class Plan:
    texts: dict[str, str]  # file -> new text
    rows: dict[str, tuple[str, set[str], str]]  # key -> (what, formatted texts, value) from this bundle
    filled: list[str]
    missing_values: list[str]
    missing_anchors: list[str]
    still_shown: set[str] = field(default_factory=set)  # keys of filled slots this bundle did not refill
    merged: list[NumRow] = field(default_factory=list)  # the NUMBERS.md rows after the merge
    skipped: list[str] = field(default_factory=list)  # slots this kind of run may not fill, with the reason
    not_placed: list[str] = field(default_factory=list)  # marker-only slots with a value but no marker in the pitch


def _put(text: str, found: Found, slot: Slot, value: str) -> str:
    return text[: found.start] + f"<!-- slot:{slot.sid} -->{value}<!-- /slot -->" + text[found.end:]


def _fill(texts: dict[str, str], slot: Slot, value: str) -> None:
    """Write ``value`` into every place of the slot (last place first, so earlier spans stay valid)."""
    for f in sorted(find(slot, texts), key=lambda f: (f.file, -f.start)):
        texts[f.file] = _put(texts[f.file], f, slot, value)


def pitch_texts(pitch_dir: Path) -> dict[str, str]:
    """Every Markdown file of the pitch folder (relative posix path -> text), plus the two the slots anchor in."""
    texts = {p.relative_to(pitch_dir).as_posix(): p.read_text(encoding="utf-8")
             for p in sorted(pitch_dir.rglob("*.md")) if p.name not in SKIP_MARKER_FILES}
    for rel in (DECK, VIDEO):
        texts.setdefault(rel, "")
    return texts


def plan(head: dict[str, Any], date: str, pitch_dir: Path, source: str = "", numbers_text: str = "",
         ev: dict[str, Any] | None = None) -> Plan:
    """What filling the pitch from this bundle changes. ``ev``: the whole bundle (its mode, place and model decide
    which slots it may fill); without it the bundle is taken as an MI300X droplet run, as before the modes."""
    ev = ev if ev is not None else {"mode": "droplet", "headline": {**head, "gpu_name": head.get("gpu_name") or "MI300X"}}
    mode, where = mode_of(ev), where_of(ev)
    if source:
        _BUNDLES[source] = ev
    texts = pitch_texts(pitch_dir)
    rows: dict[str, tuple[str, set[str], str]] = {}
    filled, missing_values, missing_anchors, skipped, not_placed = [], [], [], [], []
    still_shown: set[str] = set()
    date_only: list[Slot] = []
    for slot in ALL_SLOTS:
        places = find(slot, texts)
        keys = {k for k, _, _ in slot.keys}
        if not slot.marker_only and len(places) != 1:
            missing_anchors.append(f"{slot.sid} ({slot.file}: {len(places)} matches)")
            still_shown |= keys  # state unknown: keep the rows that may back it
            continue
        shown_before = any(not f.empty for f in places)
        why = None
        if mode not in slot.modes:
            why = f"a {mode} run does not fill it"
        elif slot.mi300x and not is_mi300x(ev):
            why = f"its text says MI300X and this run was measured on {where}"
        elif slot.gemma and not is_gemma(ev):
            why = f"its text says Gemma and the drafting model is {', '.join(drafting_models(ev))}"
        if why:
            if places and (slot.keys or slot.date_keys) and (render(slot, head, date, where)[0] is not None
                                                             if slot.keys else False):
                skipped.append(f"{slot.sid} ({why})")
            if shown_before:
                still_shown |= keys
            continue
        if not slot.keys:
            if places:
                date_only.append(slot)  # filled after the merge: they name the dates of the values they introduce
            continue
        value, slot_rows = render(slot, head, date, where)
        if value is None:
            if places:
                missing_values.append(slot.sid)
            if shown_before:
                still_shown |= keys  # an earlier bundle's value stays on the page
            continue
        if not places:
            not_placed.append(slot.sid)
            continue
        _fill(texts, slot, value)
        filled.append(slot.sid)
        for key, shown, val, what in slot_rows:
            prev = rows.get(key)
            rows[key] = (what, (prev[1] if prev else set()) | {shown}, val)
    merged = merge_rows(existing_rows(numbers_text), rows, source, still_shown) if rows else []
    current = {r.key: r.source for r in merged if r.rid == f"amd_{r.key}"}
    for slot in date_only:
        sources = sorted({current[k] for k in slot.date_keys if k in current}, key=_date_of)
        if not sources:
            missing_values.append(slot.sid)
            continue
        dates = sorted({_date_of(s) for s in sources})
        when = dates[0] if len(dates) == 1 else f"{dates[0]} to {dates[-1]}"
        places_named = list(dict.fromkeys(where_of(_bundle(s)) if _bundle(s) else where for s in sources))
        _fill(texts, slot, slot.template.format(date=when, where=_join(places_named)))
        filled.append(slot.sid)
    return Plan(texts, rows, filled, missing_values, missing_anchors, still_shown, merged, skipped, not_placed)


def numbers_section(rows: list[NumRow], gpu: str | None = None) -> str:
    sources = sorted({r.source for r in rows}, key=_date_of)
    dates = sorted({_date_of(s) for s in sources})
    places = list(dict.fromkeys(where_of(_bundle(s)) for s in sources))
    kinds = list(dict.fromkeys({"droplet": "MI300X", "notebook": "AMD ROCm notebook",
                                "endpoint": "endpoint"}.get(mode_of(_bundle(s)), "MI300X") for s in sources))
    title = gpu if (gpu and kinds == ["MI300X"]) else _join(places)
    lines = [BEGIN, f"## AMD edition: measured on {title or 'MI300X'}", "",
             "Written by `editions/amd/kickoff/fill_pitch.py --write` from the evidence bundles of the "
             f"{_join(kinds)} runs on {', '.join(dates)} (UTC). Each row re-reads `headline` in the `evidence.json` "
             "named in its Source, which `collect_evidence.py` built from that run's result files (the bundle's "
             "`compute` says where it ran). A later bundle replaces only the rows of the values it measured.", "",
             "| ID | Pitched as | Value | Source | Locator |", "|---|---|---|---|---|"]
    lines += [r.line() for r in rows]
    lines.append(END)
    return "\n".join(lines)


def with_numbers(text: str, section: str) -> str:
    if BEGIN.split(" (")[0] in text and END in text:
        start = text.index(BEGIN.split(" (")[0])
        end = text.index(END) + len(END)
        return text[:start] + section + text[end:]
    anchor = "\n## Command outputs"
    if anchor in text:
        i = text.index(anchor)
        return text[:i] + "\n" + section + "\n" + text[i:]
    return text.rstrip("\n") + "\n\n" + section + "\n"


def refuse_reason(ev: dict[str, Any], pitch_dir: Path, allow_fixture: bool) -> str | None:
    mode = mode_of(ev)
    if mode not in ANY_RUN:
        return "this is CPU-rehearsal evidence; rehearsal numbers never go into the pitch"
    if ev.get("synthetic_fixture"):
        if not allow_fixture:
            return "this is a synthetic test fixture (pass --allow-fixture with a scratch --pitch-dir)"
        if pitch_dir.resolve() == PITCH.resolve():
            return "a synthetic test fixture can never fill the real pitch/ folder"
        return None
    valid = ev.get("results_valid") if "results_valid" in ev else ev.get("gpu_results_valid")
    if not valid:
        name = "results_valid" if "results_valid" in ev else "gpu_results_valid"
        return f"{name} is false: " + "; ".join(ev.get("invalid_reasons") or ["unknown"])
    return None


def slots_table() -> str:
    lines = ["| Slot | Shows | Filled from | Found by |", "|---|---|---|---|"]
    for s in ALL_SLOTS:
        shows = s.shows or "; ".join(what for _, _, what in s.keys) or "the dates (and place) of the values it introduces"
        by = ("marker only: put `<!-- slot:" + s.sid + " -->TBD<!-- /slot -->` in any pitch/**/*.md" if s.marker_only
              else f"its text in pitch/{s.file}, or the marker")
        who = " / ".join(s.modes) + (" (MI300X only)" if s.mi300x else "") + (" (Gemma only)" if s.gemma else "")
        lines.append(f"| `{s.sid}` | {shows} | {who} | {by} |")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--evidence", default=None, help="evidence.json from collect_evidence.py")
    ap.add_argument("--write", action="store_true", help="apply the changes (default: print the diff only)")
    ap.add_argument("--pitch-dir", default=str(PITCH), help="pitch folder (tests use a copy)")
    ap.add_argument("--allow-fixture", action="store_true", help="tests only: accept a synthetic fixture bundle")
    ap.add_argument("--strict", action="store_true", help="exit 1 when a slot's anchor text is not found")
    ap.add_argument("--slots", action="store_true", help="list every slot (id, what it shows, who fills it) and exit")
    args = ap.parse_args(argv)
    if args.slots:
        print(slots_table())
        return 0
    if not args.evidence:
        ap.error("--evidence is required (or --slots)")

    ev_path = Path(args.evidence)
    ev = json.loads(ev_path.read_text(encoding="utf-8"))
    pitch_dir = Path(args.pitch_dir)
    reason = refuse_reason(ev, pitch_dir, args.allow_fixture)
    if reason:
        print(f"fill_pitch: REFUSED ({ev_path}): {reason}")
        return EXIT_REFUSED

    head = ev.get("headline") or {}
    date = str(head.get("measured_date") or ev.get("date"))
    try:
        source = ev_path.resolve().relative_to(ROOT.resolve()).as_posix()
    except ValueError:
        source = ev_path.resolve().as_posix()
    numbers_path = pitch_dir / "NUMBERS.md"
    old_numbers = numbers_path.read_text(encoding="utf-8") if numbers_path.exists() else ""
    p = plan(head, date, pitch_dir, source, old_numbers, ev)
    changes = dict(p.texts)
    if p.merged:
        changes["NUMBERS.md"] = with_numbers(old_numbers, numbers_section(p.merged, head.get("gpu_name")))

    changed = 0
    for rel, new in changes.items():
        path = pitch_dir / rel
        old = path.read_text(encoding="utf-8") if path.exists() else ""
        if new == old:
            continue
        changed += 1
        if args.write:
            path.write_text(new, encoding="utf-8", newline="\n")
        else:
            sys.stdout.writelines(difflib.unified_diff(old.splitlines(keepends=True), new.splitlines(keepends=True),
                                                       f"a/pitch/{rel}", f"b/pitch/{rel}"))
    kept = sum(1 for r in p.merged if r.source != source)
    print(f"\nfill_pitch: {len(p.filled)} slot(s) filled from {source} ({mode_of(ev)} run, {where_of(ev)}); "
          f"{len(p.rows)} NUMBERS.md row(s) from it, {kept} kept from earlier bundles; "
          f"{changed} file(s) {'written' if args.write else 'would change (dry run; --write applies)'}")
    if p.missing_values:
        print(f"  not measured in this bundle (left as they are: TBD or an earlier bundle's value): "
              f"{', '.join(p.missing_values)}")
    if p.skipped:
        print(f"  measured but not filled (the page's words do not fit this run): {'; '.join(p.skipped)}")
    if p.not_placed:
        print(f"  measured, no marker in the pitch yet (add <!-- slot:ID -->TBD<!-- /slot --> where the number "
              f"belongs; --slots lists them): {', '.join(p.not_placed)}")
    for w in ev.get("warnings") or []:
        print(f"  evidence warning: {w}")
    if p.missing_anchors:
        print(f"  anchor text not found (pitch edited?): {', '.join(p.missing_anchors)}")
    if args.write and changed:
        print("  next: uv run python pitch/check_numbers.py  (must print PASS), then commit pitch/ with the evidence")
    return 1 if (args.strict and p.missing_anchors) else 0


if __name__ == "__main__":
    sys.exit(main())
