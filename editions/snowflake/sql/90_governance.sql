-- Wapsi on Snowflake · 90 · governance, STANDARD edition variant (also the base for Enterprise):
-- RBAC grants + secure views that mask personal data and account numbers by role.
-- Enterprise accounts additionally run 91_governance_enterprise.sql (masking policies on the base tables).
-- Run as WAPSI_ADMIN after the procedures, search service, semantic view, agent and app exist.
-- Rules: no app role ever gets WAPSI.ML (ground truth) or RAW (PII); AUDIT_LOG / AUDIT_ANCHOR / APPROVALS are
-- append-only (INSERT only, never UPDATE / DELETE; audit rows are sealed into a hash chain by the case store); hold
-- amounts change only through BUILD_HOLD_PLAN or an approved account-level exception.
-- IS_ROLE_IN_SESSION('WAPSI_ANALYST') is also true for WAPSI_SUPERVISOR (role inheritance) and WAPSI_ADMIN.

USE ROLE WAPSI_ADMIN;

-- ------------------------------------------------------------------------------------------ secure views
CREATE OR REPLACE SECURE VIEW WAPSI.APP.V_CUSTOMERS
  COMMENT = 'Customers with name / mobile / PAN masked unless the viewer is an analyst'
AS
SELECT customer_id,
       IFF(IS_ROLE_IN_SESSION('WAPSI_ANALYST'), name, '***') AS name,
       IFF(IS_ROLE_IN_SESSION('WAPSI_ANALYST'), mobile, CONCAT('XXXXXX', RIGHT(mobile, 2))) AS mobile,
       IFF(IS_ROLE_IN_SESSION('WAPSI_ANALYST'), pan_masked, '***') AS pan_masked,
       kyc_tier,
       city
FROM WAPSI.RAW.CUSTOMERS;

CREATE OR REPLACE SECURE VIEW WAPSI.APP.V_COMPLAINTS
  COMMENT = 'Complaints; victim identity and narrative visible to analysts only'
AS
SELECT ncrp_id,
       reported_at,
       IFF(IS_ROLE_IN_SESSION('WAPSI_ANALYST'), victim_account,
           CONCAT(LEFT(victim_account, 5), 'XXXXXX', RIGHT(victim_account, 4))) AS victim_account,
       IFF(IS_ROLE_IN_SESSION('WAPSI_ANALYST'), victim_name, '***') AS victim_name,
       IFF(IS_ROLE_IN_SESSION('WAPSI_ANALYST'), victim_mobile, '***') AS victim_mobile,
       amount_claimed,
       IFF(IS_ROLE_IN_SESSION('WAPSI_ANALYST'), narrative_text, '[narrative withheld]') AS narrative_text,
       category,
       fir_number,
       source
FROM WAPSI.RAW.COMPLAINTS;

CREATE OR REPLACE SECURE VIEW WAPSI.APP.V_CASES
  COMMENT = 'Case totals (no personal data)'
AS
SELECT case_id, world, ncrp_ids, opened_at, status, assigned_to, stolen, total_hold, total_forward_hold,
       total_recoverable, over_hold_amount, baseline_freeze_amount, baseline_freeze_accounts,
       restoration_process, str_ground, updated_at
FROM WAPSI.CASEMGMT.CASES;

CREATE OR REPLACE SECURE VIEW WAPSI.APP.V_HOLD_PLAN
  COMMENT = 'Hold plan with account numbers masked for auditors and law-enforcement read-only users'
AS
SELECT case_id,
       IFF(IS_ROLE_IN_SESSION('WAPSI_ANALYST'), account_id,
           CONCAT(LEFT(account_id, 5), 'XXXXXX', RIGHT(account_id, 4))) AS account_id,
       bank_id, account_type, branch_city, disposition, hold_amount, forward_hold_amount, tainted_amount,
       balance_now, layer, role, citation_ids, reason_codes, requires_human
FROM WAPSI.CASEMGMT.HOLD_PLAN;

CREATE OR REPLACE SECURE VIEW WAPSI.APP.V_TRAIL_EDGES
  COMMENT = 'Money trail for law enforcement: only cases with an FIR on record; account numbers masked'
AS
SELECT e.case_id,
       e.txn_id,
       e.ts,
       IFF(IS_ROLE_IN_SESSION('WAPSI_ANALYST'), e.from_account,
           CONCAT(LEFT(e.from_account, 5), 'XXXXXX', RIGHT(e.from_account, 4))) AS from_account,
       IFF(IS_ROLE_IN_SESSION('WAPSI_ANALYST'), e.to_account,
           CONCAT(LEFT(e.to_account, 5), 'XXXXXX', RIGHT(e.to_account, 4))) AS to_account,
       e.channel, e.utr, e.amount, e.depth, e.tainted_total
FROM WAPSI.CASEMGMT.TRAIL_EDGES e
WHERE IS_ROLE_IN_SESSION('WAPSI_ANALYST')
   OR EXISTS (SELECT 1 FROM WAPSI.CASEMGMT.CASE_BUNDLES b, LATERAL FLATTEN(input => b.bundle:complaints) c
              WHERE b.case_id = e.case_id AND c.value:fir_number IS NOT NULL
                AND c.value:fir_number::STRING <> '');

