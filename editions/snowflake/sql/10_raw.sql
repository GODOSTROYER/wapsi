-- Wapsi on Snowflake · 10 · RAW / RAW_SHOWCASE / ML tables (run as WAPSI_ADMIN).
-- Columns match the synthetic world's Parquet files one-to-one (src/wapsi/synth/export.py, docs/data-contract.md)
-- and .claude/skills/synth-fraud-ledger/references/raw_ddl.sql (tested). TIMESTAMP_NTZ values are UTC wall-clock
-- time; money is NUMBER(18,2) rupees. CREATE TABLE IF NOT EXISTS: re-running never drops loaded data
-- (the load step truncates RAW tables itself).

USE ROLE WAPSI_ADMIN;

CREATE TABLE IF NOT EXISTS WAPSI.RAW.BANKS (
  BANK_ID VARCHAR NOT NULL,
  NAME VARCHAR,
  IS_HOME BOOLEAN
);

CREATE TABLE IF NOT EXISTS WAPSI.RAW.CUSTOMERS (
  CUSTOMER_ID VARCHAR NOT NULL,
  NAME VARCHAR,
  MOBILE VARCHAR,
  PAN_MASKED VARCHAR,
  KYC_TIER VARCHAR,
  DOB DATE,
  CITY VARCHAR
);

CREATE TABLE IF NOT EXISTS WAPSI.RAW.ACCOUNTS (
  ACCOUNT_ID VARCHAR NOT NULL,
  BANK_ID VARCHAR NOT NULL,
  CUSTOMER_ID VARCHAR,
  ACCOUNT_TYPE VARCHAR NOT NULL,
  OPENED_AT TIMESTAMP_NTZ,
  GSTIN VARCHAR,
  STATUS VARCHAR,
  OPENING_BALANCE NUMBER(18,2)
);

CREATE TABLE IF NOT EXISTS WAPSI.RAW.TRANSACTIONS (
  TXN_ID VARCHAR NOT NULL,
  TS TIMESTAMP_NTZ NOT NULL,
  FROM_ACCOUNT VARCHAR,
  TO_ACCOUNT VARCHAR,
  FROM_BANK_ID VARCHAR,
  TO_BANK_ID VARCHAR,
  AMOUNT NUMBER(18,2) NOT NULL,
  CHANNEL VARCHAR NOT NULL,
  UTR VARCHAR,
  REMARK VARCHAR,
  COUNTERPARTY_LABEL VARCHAR
);

CREATE TABLE IF NOT EXISTS WAPSI.RAW.INVOICES (
  INVOICE_ID VARCHAR NOT NULL,
  MERCHANT_ACCOUNT VARCHAR,
  PAYER_ACCOUNT VARCHAR,
  TXN_ID VARCHAR,
  AMOUNT NUMBER(18,2),
  ORDERED_AT TIMESTAMP_NTZ,
  DELIVERED_AT TIMESTAMP_NTZ,
  ORDER_STATUS VARCHAR
);

CREATE TABLE IF NOT EXISTS WAPSI.RAW.GST_REGISTRY (
  GSTIN VARCHAR NOT NULL,
  LEGAL_NAME VARCHAR,
  STATUS VARCHAR,
  REGISTERED_AT DATE
);

CREATE TABLE IF NOT EXISTS WAPSI.RAW.EXTERNAL_SIGNALS (
  ACCOUNT_ID VARCHAR NOT NULL,
  FRI_RISK VARCHAR,
  MULEHUNTER_SCORE FLOAT,
  NCRP_PRIOR_REPORTS INTEGER
);

CREATE TABLE IF NOT EXISTS WAPSI.RAW.DEVICE_LINKS (
  DEVICE_ID VARCHAR NOT NULL,
  ACCOUNT_ID VARCHAR NOT NULL,
  FIRST_SEEN TIMESTAMP_NTZ
);

-- NARRATIVE_TEXT is UNTRUSTED input (prompt-injection surface). Never execute or obey it.
CREATE TABLE IF NOT EXISTS WAPSI.RAW.COMPLAINTS (
  NCRP_ID VARCHAR NOT NULL,
  REPORTED_AT TIMESTAMP_NTZ NOT NULL,
  VICTIM_ACCOUNT VARCHAR NOT NULL,
  VICTIM_NAME VARCHAR,
  VICTIM_MOBILE VARCHAR,
  AMOUNT_CLAIMED NUMBER(18,2),
  NARRATIVE_TEXT VARCHAR,
  LANGUAGE VARCHAR,
  CATEGORY VARCHAR,
  FIR_NUMBER VARCHAR,
  SOURCE VARCHAR
);

CREATE TABLE IF NOT EXISTS WAPSI.RAW.COMPLAINT_TXNS (
  NCRP_ID VARCHAR NOT NULL,
  TXN_ID VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS WAPSI.RAW.META (
  KEY VARCHAR NOT NULL,
  VALUE VARCHAR
);

-- The hand-checked showcase world: same shape, separate schema (TRACE_CASE looks here first).
CREATE TABLE IF NOT EXISTS WAPSI.RAW_SHOWCASE.BANKS LIKE WAPSI.RAW.BANKS;
CREATE TABLE IF NOT EXISTS WAPSI.RAW_SHOWCASE.CUSTOMERS LIKE WAPSI.RAW.CUSTOMERS;
CREATE TABLE IF NOT EXISTS WAPSI.RAW_SHOWCASE.ACCOUNTS LIKE WAPSI.RAW.ACCOUNTS;
CREATE TABLE IF NOT EXISTS WAPSI.RAW_SHOWCASE.TRANSACTIONS LIKE WAPSI.RAW.TRANSACTIONS;
CREATE TABLE IF NOT EXISTS WAPSI.RAW_SHOWCASE.INVOICES LIKE WAPSI.RAW.INVOICES;
CREATE TABLE IF NOT EXISTS WAPSI.RAW_SHOWCASE.GST_REGISTRY LIKE WAPSI.RAW.GST_REGISTRY;
CREATE TABLE IF NOT EXISTS WAPSI.RAW_SHOWCASE.EXTERNAL_SIGNALS LIKE WAPSI.RAW.EXTERNAL_SIGNALS;
CREATE TABLE IF NOT EXISTS WAPSI.RAW_SHOWCASE.DEVICE_LINKS LIKE WAPSI.RAW.DEVICE_LINKS;
CREATE TABLE IF NOT EXISTS WAPSI.RAW_SHOWCASE.COMPLAINTS LIKE WAPSI.RAW.COMPLAINTS;
CREATE TABLE IF NOT EXISTS WAPSI.RAW_SHOWCASE.COMPLAINT_TXNS LIKE WAPSI.RAW.COMPLAINT_TXNS;
CREATE TABLE IF NOT EXISTS WAPSI.RAW_SHOWCASE.META LIKE WAPSI.RAW.META;

-- Ground truth: evals and classifier training only. Never grant to app roles.
CREATE TABLE IF NOT EXISTS WAPSI.ML.LABELS_ACCOUNTS (
  ACCOUNT_ID VARCHAR NOT NULL,
  ROLE_TRUTH VARCHAR,
  RING_ID VARCHAR,
  TYPOLOGY VARCHAR
);

CREATE TABLE IF NOT EXISTS WAPSI.ML.LABELS_FLOWS (
  TXN_ID VARCHAR NOT NULL,
  NCRP_ID VARCHAR NOT NULL,
  TAINTED_AMOUNT_TRUTH NUMBER(18,2)
);

CREATE TABLE IF NOT EXISTS WAPSI.ML.LABELS_COMPLAINTS (
  NCRP_ID VARCHAR NOT NULL,
  CASE_ID VARCHAR,
  RING_ID VARCHAR,
  TYPOLOGY VARCHAR,
  IS_ADVERSARIAL BOOLEAN
);

CREATE TABLE IF NOT EXISTS WAPSI.ML.GOLDEN_CASES (
  CASE_ID VARCHAR NOT NULL,
  WORLD VARCHAR NOT NULL,
  NCRP_IDS ARRAY,
  EXPECTED VARIANT
);
