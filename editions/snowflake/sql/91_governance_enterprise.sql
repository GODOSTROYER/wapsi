-- Wapsi on Snowflake · 91 · governance, ENTERPRISE edition variant: masking policies on the base tables.
-- Runs after 90_governance.sql (RBAC + secure views). On a Standard account the first CREATE MASKING POLICY
-- fails with an edition error; deploy.py --edition auto then reports "Standard" and keeps the 90 variant.
-- Account numbers stay clear for the builders, the procedures (owner WAPSI_ADMIN), analysts / supervisors,
-- the Streamlit owner and the actions runner; auditors and law-enforcement read-only users see them masked.
-- The procedures run with owner's rights, so CURRENT_ROLE() is also checked (owner context).

USE ROLE WAPSI_ADMIN;

CREATE MASKING POLICY IF NOT EXISTS WAPSI.APP.MASK_ACCOUNT_ID AS (val STRING) RETURNS STRING ->
  CASE
    WHEN val IS NULL THEN NULL
    WHEN CURRENT_ROLE() IN ('WAPSI_ADMIN', 'WAPSI_APP_OWNER', 'WAPSI_ACTIONS_RUNNER')
      OR IS_ROLE_IN_SESSION('WAPSI_ANALYST')
      OR IS_ROLE_IN_SESSION('WAPSI_APP_OWNER')
      OR IS_ROLE_IN_SESSION('WAPSI_ACTIONS_RUNNER') THEN val
    ELSE CONCAT(LEFT(val, 5), REPEAT('X', GREATEST(LENGTH(val) - 9, 0)), RIGHT(val, 4))
  END
  COMMENT = 'Account numbers: clear for makers / checkers / owners, masked (HB01-XXXXXX0001) for everyone else';

CREATE MASKING POLICY IF NOT EXISTS WAPSI.APP.MASK_PII AS (val STRING) RETURNS STRING ->
  CASE
    WHEN val IS NULL THEN NULL
    WHEN CURRENT_ROLE() IN ('WAPSI_ADMIN', 'WAPSI_APP_OWNER') OR IS_ROLE_IN_SESSION('WAPSI_ANALYST') THEN val
    ELSE '***'
  END
  COMMENT = 'Names, mobiles, PAN and complaint narratives: analysts only';

-- Account numbers in the case tables the auditor / LEA roles can reach.
ALTER TABLE WAPSI.CASEMGMT.HOLD_PLAN MODIFY COLUMN ACCOUNT_ID SET MASKING POLICY WAPSI.APP.MASK_ACCOUNT_ID FORCE;
ALTER TABLE WAPSI.CASEMGMT.ACCOUNT_STATE MODIFY COLUMN ACCOUNT_ID SET MASKING POLICY WAPSI.APP.MASK_ACCOUNT_ID FORCE;
ALTER TABLE WAPSI.CASEMGMT.TRAIL_EDGES MODIFY COLUMN FROM_ACCOUNT SET MASKING POLICY WAPSI.APP.MASK_ACCOUNT_ID FORCE;
ALTER TABLE WAPSI.CASEMGMT.TRAIL_EDGES MODIFY COLUMN TO_ACCOUNT SET MASKING POLICY WAPSI.APP.MASK_ACCOUNT_ID FORCE;
ALTER TABLE WAPSI.CASEMGMT.LIENS MODIFY COLUMN ACCOUNT_ID SET MASKING POLICY WAPSI.APP.MASK_ACCOUNT_ID FORCE;
ALTER TABLE WAPSI.RAW.COMPLAINTS MODIFY COLUMN VICTIM_ACCOUNT SET MASKING POLICY WAPSI.APP.MASK_ACCOUNT_ID FORCE;

-- Personal data in RAW (the product reads RAW only through owner's-rights procedures).
ALTER TABLE WAPSI.RAW.CUSTOMERS MODIFY COLUMN NAME SET MASKING POLICY WAPSI.APP.MASK_PII FORCE;
ALTER TABLE WAPSI.RAW.CUSTOMERS MODIFY COLUMN MOBILE SET MASKING POLICY WAPSI.APP.MASK_PII FORCE;
ALTER TABLE WAPSI.RAW.CUSTOMERS MODIFY COLUMN PAN_MASKED SET MASKING POLICY WAPSI.APP.MASK_PII FORCE;
ALTER TABLE WAPSI.RAW.COMPLAINTS MODIFY COLUMN VICTIM_NAME SET MASKING POLICY WAPSI.APP.MASK_PII FORCE;
ALTER TABLE WAPSI.RAW.COMPLAINTS MODIFY COLUMN VICTIM_MOBILE SET MASKING POLICY WAPSI.APP.MASK_PII FORCE;
ALTER TABLE WAPSI.RAW.COMPLAINTS MODIFY COLUMN NARRATIVE_TEXT SET MASKING POLICY WAPSI.APP.MASK_PII FORCE;

-- Auditors may read the base hold plan too (masked by the policy, not by a view).
GRANT SELECT ON TABLE WAPSI.CASEMGMT.HOLD_PLAN TO ROLE WAPSI_AUDITOR;

SHOW MASKING POLICIES IN SCHEMA WAPSI.APP;
