-- Wapsi on Snowflake · 00 · account objects: roles, warehouse, resource monitor, Cortex access.
-- Run as ACCOUNTADMIN (deploy.py --step bootstrap, or: snow sql -c <connection> -f editions/snowflake/sql/00_account.sql).
-- Idempotent: IF NOT EXISTS everywhere; re-running re-applies the cost guardrails.
-- Statements marked "-- @optional" may fail on some accounts; deploy.py reports them and continues.

USE ROLE ACCOUNTADMIN;

-- Roles (README "Snowflake objects"): build/owner, Streamlit owner, maker, checker, read-only, drain, ML.
CREATE ROLE IF NOT EXISTS WAPSI_ADMIN COMMENT = 'Wapsi build and object owner';
CREATE ROLE IF NOT EXISTS WAPSI_APP_OWNER COMMENT = 'Owns the Streamlit app (owner''s rights); no access to WAPSI.ML';
CREATE ROLE IF NOT EXISTS WAPSI_ANALYST COMMENT = 'Nodal officer (maker): trace, plan, draft, verify';
CREATE ROLE IF NOT EXISTS WAPSI_SUPERVISOR COMMENT = 'Supervisor (checker): approves drafts; inherits WAPSI_ANALYST';
CREATE ROLE IF NOT EXISTS WAPSI_AUDITOR COMMENT = 'Read-only audit; personal data masked';
CREATE ROLE IF NOT EXISTS WAPSI_LEA_READONLY COMMENT = 'Law-enforcement read-only view of trails; masked';
CREATE ROLE IF NOT EXISTS WAPSI_ACTIONS_RUNNER COMMENT = 'Drains CASEMGMT.ACTIONS (Jira/Slack runner)';
CREATE ROLE IF NOT EXISTS WAPSI_ML COMMENT = 'Ground truth, golden set and evaluations (WAPSI.ML)';

GRANT ROLE WAPSI_ANALYST TO ROLE WAPSI_SUPERVISOR;
GRANT ROLE WAPSI_SUPERVISOR TO ROLE WAPSI_ADMIN;
GRANT ROLE WAPSI_APP_OWNER TO ROLE WAPSI_ADMIN;
GRANT ROLE WAPSI_AUDITOR TO ROLE WAPSI_ADMIN;
GRANT ROLE WAPSI_LEA_READONLY TO ROLE WAPSI_ADMIN;
GRANT ROLE WAPSI_ACTIONS_RUNNER TO ROLE WAPSI_ADMIN;
GRANT ROLE WAPSI_ML TO ROLE WAPSI_ADMIN;
GRANT ROLE WAPSI_ADMIN TO ROLE SYSADMIN;

-- One small warehouse; the guard hook blocks sizes above SMALL and AUTO_SUSPEND above 300 s.
CREATE WAREHOUSE IF NOT EXISTS WAPSI_WH WITH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 300
  COMMENT = 'Wapsi: the only warehouse (XS, 60 s auto-suspend, 300 s statement timeout)';
ALTER WAREHOUSE WAPSI_WH SET
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 300;

-- Credit cap (warehouses only; watch Cortex / serverless spend on the cost page).
CREATE RESOURCE MONITOR IF NOT EXISTS WAPSI_RM WITH
  CREDIT_QUOTA = 20
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 50 PERCENT DO NOTIFY
           ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND
           ON 110 PERCENT DO SUSPEND_IMMEDIATE;
ALTER WAREHOUSE WAPSI_WH SET RESOURCE_MONITOR = WAPSI_RM;

GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE WAPSI_WH TO ROLE WAPSI_ADMIN;
GRANT USAGE ON WAREHOUSE WAPSI_WH TO ROLE WAPSI_APP_OWNER;
GRANT USAGE ON WAREHOUSE WAPSI_WH TO ROLE WAPSI_ANALYST;
GRANT USAGE ON WAREHOUSE WAPSI_WH TO ROLE WAPSI_AUDITOR;
GRANT USAGE ON WAREHOUSE WAPSI_WH TO ROLE WAPSI_LEA_READONLY;
GRANT USAGE ON WAREHOUSE WAPSI_WH TO ROLE WAPSI_ACTIONS_RUNNER;
GRANT USAGE ON WAREHOUSE WAPSI_WH TO ROLE WAPSI_ML;

-- Account privileges for the build role.
GRANT CREATE DATABASE ON ACCOUNT TO ROLE WAPSI_ADMIN;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE WAPSI_ADMIN;
-- @optional
GRANT EXECUTE MANAGED TASK ON ACCOUNT TO ROLE WAPSI_ADMIN;
-- @optional
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE TO ROLE WAPSI_ADMIN;

-- Cortex (AI_COMPLETE, Cortex Search, Analyst, Agents).
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE WAPSI_ADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE WAPSI_ANALYST;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE WAPSI_APP_OWNER;

-- The person running the deploy gets every Wapsi role (one human runs the role tests).
SET WAPSI_ME = CURRENT_USER();
-- @optional
GRANT ROLE WAPSI_ADMIN TO USER IDENTIFIER($WAPSI_ME);
-- @optional
GRANT ROLE WAPSI_APP_OWNER TO USER IDENTIFIER($WAPSI_ME);
-- @optional
GRANT ROLE WAPSI_ANALYST TO USER IDENTIFIER($WAPSI_ME);
-- @optional
GRANT ROLE WAPSI_SUPERVISOR TO USER IDENTIFIER($WAPSI_ME);
-- @optional
GRANT ROLE WAPSI_AUDITOR TO USER IDENTIFIER($WAPSI_ME);
-- @optional
GRANT ROLE WAPSI_LEA_READONLY TO USER IDENTIFIER($WAPSI_ME);
-- @optional
GRANT ROLE WAPSI_ACTIONS_RUNNER TO USER IDENTIFIER($WAPSI_ME);
-- @optional
GRANT ROLE WAPSI_ML TO USER IDENTIFIER($WAPSI_ME);

SHOW WAREHOUSES LIKE 'WAPSI_WH';
