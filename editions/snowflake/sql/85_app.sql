-- Wapsi on Snowflake · 85 · Streamlit in Snowflake app WAPSI.APP.WAPSI_APP (warehouse runtime).
-- deploy.py --step app first uploads to @WAPSI.APP.SIS_STAGE/wapsi/: streamlit_app.py, sf_data_source.py,
-- environment.yml (Snowflake Anaconda channel) and wapsi_app.zip (core + wapsi_sf + the shared ui package).
-- The app is owned by WAPSI_APP_OWNER (owner's rights, no access to WAPSI.ML or RAW) and calls the case
-- procedures; approvals go through APPROVE with the viewer's persona (APP.USER_ROLES), checker != maker.
-- Warehouse runtime on purpose: the container runtime needs a compute pool and PyPI egress (not on trials).

USE ROLE WAPSI_ADMIN;

-- What the app owner may touch (read case tables, call the procedures, append approvals / audit).
GRANT USAGE ON DATABASE WAPSI TO ROLE WAPSI_APP_OWNER;
GRANT USAGE ON SCHEMA WAPSI.APP TO ROLE WAPSI_APP_OWNER;
GRANT USAGE ON SCHEMA WAPSI.CASEMGMT TO ROLE WAPSI_APP_OWNER;
GRANT CREATE STREAMLIT ON SCHEMA WAPSI.APP TO ROLE WAPSI_APP_OWNER;
GRANT READ, WRITE ON STAGE WAPSI.APP.SIS_STAGE TO ROLE WAPSI_APP_OWNER;
GRANT READ ON STAGE WAPSI.APP.CODE TO ROLE WAPSI_APP_OWNER;
GRANT SELECT ON ALL TABLES IN SCHEMA WAPSI.CASEMGMT TO ROLE WAPSI_APP_OWNER;
GRANT SELECT ON ALL VIEWS IN SCHEMA WAPSI.CASEMGMT TO ROLE WAPSI_APP_OWNER;
GRANT SELECT ON TABLE WAPSI.APP.USER_ROLES TO ROLE WAPSI_APP_OWNER;
GRANT SELECT ON TABLE WAPSI.APP.EVAL_RUNS TO ROLE WAPSI_APP_OWNER;
GRANT SELECT ON TABLE WAPSI.APP.SETTINGS TO ROLE WAPSI_APP_OWNER;
GRANT USAGE ON PROCEDURE WAPSI.CASEMGMT.TRACE_CASE(VARCHAR) TO ROLE WAPSI_APP_OWNER;
GRANT USAGE ON PROCEDURE WAPSI.CASEMGMT.BUILD_HOLD_PLAN(VARCHAR) TO ROLE WAPSI_APP_OWNER;
GRANT USAGE ON PROCEDURE WAPSI.CASEMGMT.CASE_SUMMARY(VARCHAR) TO ROLE WAPSI_APP_OWNER;
GRANT USAGE ON PROCEDURE WAPSI.CASEMGMT.DRAFT(VARCHAR, VARCHAR) TO ROLE WAPSI_APP_OWNER;
GRANT USAGE ON PROCEDURE WAPSI.CASEMGMT.VERIFY(VARCHAR) TO ROLE WAPSI_APP_OWNER;
GRANT USAGE ON PROCEDURE WAPSI.CASEMGMT.APPROVE(VARCHAR, VARCHAR, VARCHAR, VARCHAR, VARCHAR) TO ROLE WAPSI_APP_OWNER;
GRANT USAGE ON PROCEDURE WAPSI.CASEMGMT.APPROVE_ACCOUNT_LEVEL(VARCHAR, VARCHAR, VARCHAR, VARCHAR) TO ROLE WAPSI_APP_OWNER;
GRANT USAGE ON PROCEDURE WAPSI.CASEMGMT.REQUEST_ACCOUNT_LEVEL_HOLD(VARCHAR, VARCHAR, VARCHAR, VARCHAR, VARCHAR) TO ROLE WAPSI_APP_OWNER;
GRANT USAGE ON PROCEDURE WAPSI.CASEMGMT.CHECK_LEA(VARCHAR, VARCHAR, VARCHAR) TO ROLE WAPSI_APP_OWNER;
-- APPROVE runs with caller's rights: the narrow DML it needs (same as WAPSI_SUPERVISOR in 90_governance.sql);
-- audit rows and anchors are INSERT-only, sealed by the case store.
GRANT INSERT ON TABLE WAPSI.CASEMGMT.APPROVALS TO ROLE WAPSI_APP_OWNER;
GRANT INSERT ON TABLE WAPSI.CASEMGMT.ACTIONS TO ROLE WAPSI_APP_OWNER;
GRANT INSERT ON TABLE WAPSI.CASEMGMT.LIENS TO ROLE WAPSI_APP_OWNER;
GRANT INSERT ON TABLE WAPSI.CASEMGMT.AUDIT_LOG TO ROLE WAPSI_APP_OWNER;
GRANT INSERT ON TABLE WAPSI.CASEMGMT.AUDIT_ANCHOR TO ROLE WAPSI_APP_OWNER;
GRANT INSERT, DELETE ON TABLE WAPSI.CASEMGMT.CLOCKS TO ROLE WAPSI_APP_OWNER;
GRANT UPDATE ON TABLE WAPSI.CASEMGMT.CASE_BUNDLES TO ROLE WAPSI_APP_OWNER;
GRANT UPDATE ON TABLE WAPSI.CASEMGMT.CASES TO ROLE WAPSI_APP_OWNER;

USE ROLE WAPSI_APP_OWNER;

CREATE OR REPLACE STREAMLIT WAPSI.APP.WAPSI_APP
  FROM '@WAPSI.APP.SIS_STAGE/wapsi'
  MAIN_FILE = 'streamlit_app.py'
  QUERY_WAREHOUSE = WAPSI_WH
  RUNTIME_NAME = 'SYSTEM$WAREHOUSE_RUNTIME'
  TITLE = 'Wapsi · Money-trail copilot'
  COMMENT = 'Nodal officer case room: trail, amount-specific holds, verified drafts, maker-checker (synthetic data)';

GRANT USAGE ON STREAMLIT WAPSI.APP.WAPSI_APP TO ROLE WAPSI_ANALYST;
GRANT USAGE ON STREAMLIT WAPSI.APP.WAPSI_APP TO ROLE WAPSI_AUDITOR;

USE ROLE WAPSI_ADMIN;
SHOW STREAMLITS IN SCHEMA WAPSI.APP;
